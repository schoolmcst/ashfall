#!/usr/bin/env python3
"""Build game/src/news.js (the main-menu NEWS panel) from the public release history in git, plus any extra
version passed as JSON on stdin ({"version":..., "notes":[...]}) for the patch being prepared."""
import json, subprocess, sys
out, seen = [], set()
hs = subprocess.check_output(['git', 'log', '--format=%H %ad', '--date=short', '--', 'release/version.json'], text=True).split('\n')
for line in hs:
    if not line.strip(): continue
    h, d = line.split()
    try: j = json.loads(subprocess.check_output(['git', 'show', f'{h}:release/version.json'], text=True))
    except Exception: continue
    if j['version'] in seen: continue
    seen.add(j['version']); out.append({'v': j['version'], 'd': d, 'n': j.get('notes', [])})
extra = sys.stdin.read().strip() if not sys.stdin.isatty() else ''
if extra:
    e = json.loads(extra)
    if e['version'] not in seen: out.insert(0, {'v': e['version'], 'd': e.get('date', out[0]['d'] if out else ''), 'n': e['notes']})
NAMES = {'1.2.0': 'PROJECT HOMECOMING · MAJOR UPDATE'}   # named updates
for o in out:
    if o['v'] in NAMES: o['name'] = NAMES[o['v']]
open('game/src/news.js', 'w').write('/* generated by tools/mknews.py: patch history for the NEWS panel (newest first) */\nconst NEWS = ' + json.dumps(out, ensure_ascii=False, indent=0) + ';\n')
print(len(out), 'versions')
