#!/usr/bin/env python3
"""Builds game/src/samples.js: recorded CC0 sounds, trimmed, normalised, mono Ogg Vorbis, base64.
Sources (all CC0, cloned from GitHub):
  GF  = https://github.com/bonesvt/GodotFall            assets/audio/sfx  (cut from CC0 OpenGameArt packs; its README lists every pack)
  PM  = https://github.com/PanderMusubi/sound-effects-library-weapons  samples (Still North Media, Free Firearm Sound Library)
usage: build_sounds.py <GodotFall clone> <sound-effects-library-weapons clone> <out samples.js>"""
import sys, subprocess, base64, json, os, tempfile
gf, pm, out = sys.argv[1], sys.argv[2], sys.argv[3]
S = os.path.join(gf, 'assets/audio/sfx')
# name: (file, start, duration or None, fade-out seconds)
SPEC = {
  'shot_ak':   (f'{S}/grunt_shot.ogg', 0, None, 0.15),        # AK-47 (Free Firearm Sound Library)
  'shot_smg':  (f'{pm}/samples/ppsh_P_22P.ogg', 1.628, 0.85, 0.5),  # last round of a PPSh burst, with its tail
  'shot_pistol': (f'{S}/far_shot_3.ogg', 0, None, 0.15),      # .22 Magnum
  'shot_sup':  (f'{S}/pistol.ogg', 0, None, 0.08),            # suppressed pistol
  'far_1':     (f'{S}/far_shot_1.ogg', 0, None, 0.15),
  'far_2':     (f'{S}/far_shot_2.ogg', 0, None, 0.15),
  'boom':      (f'{S}/explosion_big.ogg', 0, 2.2, 0.9),
  'boom_far':  (f'{S}/explosion_far.ogg', 0, 2.2, 0.9),
  'reload_out': (f'{S}/reload_out.ogg', 0, None, 0.05),
  'reload_in': (f'{S}/reload_in.ogg', 0, None, 0.05),
  'mag_drop':  (f'{S}/mag_drop.ogg', 0, None, 0.05),
  'dry':       (f'{S}/dry_click.ogg', 0, None, 0.03),
  'casing':    (f'{S}/shell_casing.ogg', 0, None, 0.03),
  'step1':     (f'{S}/step_concrete_1.ogg', 0, None, 0.02),
  'step2':     (f'{S}/step_concrete_2.ogg', 0, None, 0.02),
  'step3':     (f'{S}/step_concrete_3.ogg', 0, None, 0.02),
  'step4':     (f'{S}/step_concrete_4.ogg', 0, None, 0.02),
}
res, tot = {}, 0
with tempfile.TemporaryDirectory() as td:
  for k, (f, st, du, fo) in SPEC.items():
    o = os.path.join(td, k + '.ogg')
    dur = du if du else float(subprocess.check_output(['ffprobe', '-v', 'error', '-show_entries', 'format=duration', '-of', 'csv=p=0', f]).decode()) - st
    # peak-normalise everything to -1 dBFS (second pass) so levels are predictable in the game
    tmp = os.path.join(td, k + '.wav')
    subprocess.check_call(['ffmpeg', '-v', 'error', '-y', '-ss', str(st), '-t', f'{dur:.3f}', '-i', f, '-ac', '1', '-ar', '44100', '-af', f'afade=t=out:st={max(0, dur - fo):.3f}:d={fo}', tmp])
    peak = subprocess.run(['ffmpeg', '-v', 'info', '-i', tmp, '-af', 'volumedetect', '-f', 'null', '-'], capture_output=True, text=True).stderr
    mx = float([l for l in peak.splitlines() if 'max_volume' in l][0].split(':')[1].split()[0])
    subprocess.check_call(['ffmpeg', '-v', 'error', '-y', '-i', tmp, '-af', f'volume={-1 - mx:.2f}dB', '-ar', '32000', '-c:a', 'libvorbis', '-q:a', '4', o])
    b = open(o, 'rb').read(); tot += len(b); res[k] = base64.b64encode(b).decode()
js = ('/* recorded sounds (CC0), generated by tools/sounds/build_sounds.py: do not edit by hand */\n'
      'const SAMPLE_B64 = ' + json.dumps(res, separators=(',', ':')).replace('","', '",\n"') + ';\n')
open(out, 'w').write(js)
print('samples', len(res), 'ogg bytes', tot, 'js bytes', len(js))
